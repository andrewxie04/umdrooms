/**
 * Ground lobby furniture traced from the official UMD / HDR 2023 event guide.
 * Original PDF page index 6, 576 x 576 pt; origin top-left, +x right, +y down.
 * Data only: apply the shared Ground guide registration in the consumer.
 * Sampled points are rounded to 0.00001 pt. Raw source commands retain the
 * original PyMuPDF floating-point coordinates and get_drawings() indices.
 * One chair and two table outlines are recovered from PDF vector paths behind
 * the callout and labeled with provenance. No covered geometry is guessed.
 * This historical diagram does not establish current movable furniture.
 */

export type LobbyDiagramPoint = readonly [pdfX: number, pdfY: number];
/** Closed boundaries without a repeated closing point; +area is clockwise in PDF axes. */
export type LobbyDiagramPolygon = readonly LobbyDiagramPoint[];
export type LobbyDiagramPolyline = readonly LobbyDiagramPoint[];

export type LobbyDiagramSourceCommand =
  | readonly ['l', from: LobbyDiagramPoint, to: LobbyDiagramPoint]
  | readonly [
      'c',
      from: LobbyDiagramPoint,
      control1: LobbyDiagramPoint,
      control2: LobbyDiagramPoint,
      to: LobbyDiagramPoint,
    ];

export interface LobbyDiagramSourcePath {
  /** Zero-based index from page.get_drawings(), using the original page. */
  readonly pathIndex: number;
  readonly commands: readonly LobbyDiagramSourceCommand[];
}

export interface LobbySofaDiagramRecord {
  /** IDs describe positions on the PDF page, not geographic bearings. */
  readonly id: string;
  /** Full outside footprint; the back strip is a subset of this footprint. */
  readonly seat: LobbyDiagramPolygon;
  /** Empty when the symbol has no visible back-strip line. */
  readonly back: LobbyDiagramPolygon;
  readonly backStatus: 'traced' | 'not-drawn';
  readonly seatSourcePathIndices: readonly number[];
  readonly backInsetSourcePathIndices: readonly number[];
}

export interface LobbyChairDiagramRecord {
  readonly id: string;
  readonly provenance: 'visible-on-page' | 'recovered-behind-callout';
  /** Recovered chair retains the entire glyph; other chairs retain direction curves. */
  readonly sourcePathIndices: readonly number[];
  /** Midpoint between the source front and back curves at parameter t=0.5. */
  readonly center: LobbyDiagramPoint;
  /** Point on the back curve: back - center is the PDF back direction. */
  readonly back: LobbyDiagramPoint;
  readonly front: LobbyDiagramPoint;
  /** Diagram glyph sizes in pt, not physical chair dimensions. */
  readonly symbolWidthPt: number;
  readonly symbolDepthPt: number;
  readonly backSourcePathIndex: number;
  readonly frontSourcePathIndex: number;
}

export interface LobbyTableDiagramRecord {
  readonly id: string;
  readonly provenance: 'visible-on-page' | 'recovered-behind-callout';
  readonly pairId: string;
  /** Circle fitted to complete source curves, including verified recovered curves. */
  readonly center: LobbyDiagramPoint;
  readonly radius: number;
  readonly visibility: 'complete' | 'partly-obscured';
  /** Both original path fragments are retained, including recovered portions. */
  readonly sourcePathIndices: readonly number[];
  /** Open polylines clipped to the visible portions outside the yellow marker. */
  readonly visibleOutline: readonly LobbyDiagramPolyline[];
  readonly radiusFitMaxResidualPt: number;
}

