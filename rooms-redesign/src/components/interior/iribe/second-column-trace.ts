export type SecondColumnDiagramPoint = readonly [pdfX: number, pdfY: number];
export type SecondColumnDiagramBounds = readonly [xMin: number, yMin: number, xMax: number, yMax: number];
export type SecondColumnDiagramColor = readonly [red: number, green: number, blue: number];
export type SecondColumnCenterDerivation = 'control-bounds-midpoint' | 'curve-bounds-midpoint';

export type SecondColumnDiagramSourceCommand =
  | readonly ['l', from: SecondColumnDiagramPoint, to: SecondColumnDiagramPoint]
  | readonly [
      'c',
      from: SecondColumnDiagramPoint,
      control1: SecondColumnDiagramPoint,
      control2: SecondColumnDiagramPoint,
      to: SecondColumnDiagramPoint,
    ]
  | readonly ['re', bounds: SecondColumnDiagramBounds, orientation: 1 | -1];

export interface SecondColumnDiagramRecord {
  readonly id: string;
  /** Page 10 center estimate; centerDerivation makes it reproducible. */
  readonly center: SecondColumnDiagramPoint;
  readonly centerSourcePathIndex: number;
  readonly centerDerivation: SecondColumnCenterDerivation;
  /** Mean x/y half-extent of the actual outer curves, evaluated at extrema. */
  readonly markerRadiusPt: number;
  /** Mean x/y half-extent of get_drawings().rect, including Bezier controls. */
  readonly markerControlBoundsRadiusPt: number;
  readonly markerCurveBoundsPt: SecondColumnDiagramBounds;
  /** Visually interpreted relative to the source exterior glass/wall line. */
  readonly sourceBuilding: 'inside' | 'outside';
  /** Zero-based get_drawings() indices on the ORIGINAL page 10. */
  readonly sourcePathIndices: readonly number[];
  /** Matched ORIGINAL page 9 paths; translate x by -576 pt into page 10. */
  readonly page9SourcePathIndices: readonly number[];
  /** Native page 9 center, using the same derivation on its own commands. */
  readonly page9Center: SecondColumnDiagramPoint;
  /** Page-position labels, not surveyed geographic bearings. */
  readonly zone:
    | 'hatchery-and-east-wing'
    | 'room-2207-corridors'
    | 'central-core-and-north-facade'
    | 'room-2107-and-west-meeting-area'
    | 'west-office-and-support-wing';
  readonly page10Visibility: 'visible' | 'clipped-by-page-edge' | 'outside-page';
  readonly annotationOcclusion: 'none';
  readonly context: string;
}

