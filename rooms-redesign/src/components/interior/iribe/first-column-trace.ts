/**
 * Round structural column symbols traced from the official UMD / HDR Level 1 guide.
 * Original PDF page index 8: 576 x 576 pt, origin top-left, +x right, +y down.
 * Data only. Consumers apply the shared firstGuidePlan registration.
 * Radii describe illustrative vector silhouettes, never surveyed column sizes.
 * Twenty-five verified black symbols, all inside the drawn exterior line.
 * Thirteen gray furniture-associated outlines are retained separately.
 * Exact source commands include the seam marker and continuation coordinates.
 * See docs/research/iribe/first-columns-2026-10-03.md for evidence and limits.
 */

export type FirstColumnDiagramPoint = readonly [pdfX: number, pdfY: number];
export type FirstColumnDiagramBounds = readonly [xMin: number, yMin: number, xMax: number, yMax: number];
export type FirstColumnDiagramColor = readonly [red: number, green: number, blue: number];

export type FirstColumnDiagramSourceCommand =
  | readonly ['l', from: FirstColumnDiagramPoint, to: FirstColumnDiagramPoint]
  | readonly [
      'c',
      from: FirstColumnDiagramPoint,
      control1: FirstColumnDiagramPoint,
      control2: FirstColumnDiagramPoint,
      to: FirstColumnDiagramPoint,
    ]
  | readonly ['re', bounds: FirstColumnDiagramBounds, orientation: 1 | -1];

export interface FirstColumnDiagramRecord {
  readonly id: string;
  /** Original-frame center estimate; inspect centerDerivation for the method. */
  readonly center: FirstColumnDiagramPoint;
  readonly centerSourcePathIndex: number;
  readonly centerDerivation: 'control-bounds-midpoint' | 'curve-bounds-midpoint';
  /** Mean x/y half-extent of the actual outer curves, evaluated at extrema. */
  readonly markerRadiusPt: number;
  /** Mean x/y half-extent of get_drawings().rect, including Bezier controls. */
  readonly markerControlBoundsRadiusPt: number;
  readonly markerCurveBoundsPt: FirstColumnDiagramBounds;
  /** Relation to the source exterior glass/wall line, interpreted visually. */
  readonly sourceBuilding: 'inside' | 'outside';
  /** Page-position labels, not surveyed geographic bearings. */
  readonly zone:
    | 'sandbox-east-wing'
    | 'room-1207-corridors'
    | 'lobby-and-atrium'
    | 'cafe-and-west-atrium'
    | 'west-office-and-support-wing';
  readonly page8Visibility: 'visible' | 'clipped-by-page-edge' | 'outside-page';
  readonly annotationOcclusion: 'none';
  /** Zero-based get_drawings() indices on original PDF page 8. */
  readonly sourcePathIndices: readonly number[];
  /** Matching original page 7 paths; translate x by -576 pt into this frame. */
  readonly page7SourcePathIndices: readonly number[];
}

export interface FirstColumnUncertainDiagramMark {
  readonly id: string;
  readonly center: FirstColumnDiagramPoint;
  readonly centerDerivation: 'control-bounds-midpoint';
  /** Geometric curve half-extents of an unfilled outline, excluding stroke width. */
  readonly markerRadiusPt: number;
  readonly markerControlBoundsRadiusPt: number;
  readonly markerCurveBoundsPt: FirstColumnDiagramBounds;
  readonly sourceBuilding: 'inside';
  readonly sourcePathIndices: readonly number[];
  readonly page7SourcePathIndices: readonly number[];
  readonly reason: 'gray-outline-in-furniture-layout';
  readonly structuralStatus: 'not-established';
  readonly context: string;
}

export interface FirstColumnDiagramSourcePath {
  readonly pathIndex: number;
  readonly sequenceNumber: number;
  /** Original PyMuPDF rect: includes control points, not just curve extrema. */
  readonly controlBoundsPt: FirstColumnDiagramBounds;
  readonly renderType: 'f' | 's';
  readonly fill: FirstColumnDiagramColor | null;
  readonly strokeColor: FirstColumnDiagramColor | null;
  readonly fillOpacity: number | null;
  readonly strokeOpacity: number | null;
  readonly strokeWidthPt: number | null;
  readonly evenOdd: boolean | null;
  readonly closePath: boolean | null;
  readonly lineCap: readonly [number, number, number] | null;
  readonly lineJoin: number | null;
  readonly dashes: string | null;
  readonly commands: readonly FirstColumnDiagramSourceCommand[];
}

