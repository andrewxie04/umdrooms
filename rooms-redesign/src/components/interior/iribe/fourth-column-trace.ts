/**
 * Round structural symbols traced from the official UMD / HDR Level 4 guide.
 * Original PDF page index 12: 576 x 576 pt, top-left origin, +x right, +y down.
 * Twenty verified black symbols inside the source facade; five on continuation.
 * Three gray furniture outlines and five nonround details remain separate.
 * Radii measure actual illustrative cubic silhouettes, never physical diameters.
 * Both original pages retain their own unrounded commands, item IDs and styles.
 * Pure source arrays; application registration and integration are not supplied.
 * See docs/research/iribe/fourth-columns-2026-10-03.md for evidence and limits.
 */

export type FourthColumnDiagramPoint = readonly [pdfX: number, pdfY: number];
export type FourthColumnDiagramBounds = readonly [xMin: number, yMin: number, xMax: number, yMax: number];
export type FourthColumnDiagramColor = readonly [red: number, green: number, blue: number];
export type FourthColumnCenterDerivation = 'control-bounds-midpoint' | 'curve-bounds-midpoint';

export type FourthColumnDiagramSourceCommand =
  | readonly ['l', from: FourthColumnDiagramPoint, to: FourthColumnDiagramPoint]
  | readonly [
      'c',
      from: FourthColumnDiagramPoint,
      control1: FourthColumnDiagramPoint,
      control2: FourthColumnDiagramPoint,
      to: FourthColumnDiagramPoint,
    ]
  | readonly ['re', bounds: FourthColumnDiagramBounds, orientation: 1 | -1];

export interface FourthColumnDiagramRecord {
  readonly id: string;
  /** Page 12 center estimate; centerDerivation makes it reproducible. */
  readonly center: FourthColumnDiagramPoint;
  readonly centerSourcePathIndex: number;
  readonly centerDerivation: FourthColumnCenterDerivation;
  /** Mean x/y half-extent of the actual outer curves, evaluated at extrema. */
  readonly markerRadiusPt: number;
  /** Mean x/y half-extent of get_drawings().rect, including Bezier controls. */
  readonly markerControlBoundsRadiusPt: number;
  readonly markerCurveBoundsPt: FourthColumnDiagramBounds;
  /** Visually interpreted relative to the source exterior glass/wall line. */
  readonly sourceBuilding: 'inside' | 'outside';
  /** Zero-based get_drawings() indices on the ORIGINAL page 12. */
  readonly sourcePathIndices: readonly number[];
  /** Matched ORIGINAL page 11 paths; translate x by -576 pt into page 12. */
  readonly page11SourcePathIndices: readonly number[];
  /** Native page 11 center, using the same derivation on its own commands. */
  readonly page11Center: FourthColumnDiagramPoint;
  /** Page-position labels, not surveyed geographic bearings. */
  readonly zone:
    | 'east-reset-zone'
    | 'central-east-room-corridors'
    | 'central-core-and-north-facade'
    | 'room-4105-and-west-corridors'
    | 'west-reset-zone-and-support-wing';
  readonly page12Visibility: 'visible' | 'clipped-by-page-edge' | 'outside-page';
  readonly annotationOcclusion: 'none';
  readonly context: string;
}

